import { writeFileSync, readFileSync } from 'node:fs';
import { LEVELS, createCatalog } from '../packages/game-core/v3/levels.js';
import { initialState, transition, stateKey, isComplete, simulate } from '../packages/game-core/v3/rules.js';
const files = new Map();
files.set('games/godot/campaign_levels.gd', '# Generated by tools/sync-godot-campaign.mjs; edit packages/game-core/v3/levels.js.\nextends RefCounted\nconst LEVELS = ' + JSON.stringify(LEVELS, null, '\t') + '\n');
const fixtures = [];
for (const [id, entry] of createCatalog()) {
  const level = entry.compiled, queue = [initialState(level)], seen = new Set(queue.map(stateKey)), transitions = [];
  for (let i = 0; i < queue.length; i++) {
    const state = queue[i];
    for (const direction of ['up', 'down', 'left', 'right']) {
      const action = { type: 'move', direction };
      let result;
      try { result = transition(level, state, action); } catch (e) { result = { error: e.code }; }
      transitions.push({ state, direction, result });
      if (result.state && !seen.has(stateKey(result.state))) { seen.add(stateKey(result.state)); queue.push(result.state); }
    }
  }
  fixtures.push({ id, transitions, optimal: entry.solution.optimalMoveCount, actions: entry.solution.actions, simulation: simulate(level, entry.solution.actions), complete: queue.filter(s => isComplete(level, s)) });
}
files.set('games/godot/campaign_parity_test.json', JSON.stringify(fixtures));
for (const [file, content] of files) {
  if (process.argv.includes('--check')) { if (readFileSync(new URL('../' + file, import.meta.url), 'utf8').replace(/\r\n/g, '\n') !== content) throw new Error(`Stale generated file: ${file}`); }
  else writeFileSync(new URL('../' + file, import.meta.url), content);
}
console.log(`Campaign synchronized: ${fixtures.length} levels, ${fixtures.reduce((n, f) => n + f.transitions.length, 0)} reference transitions.`);
